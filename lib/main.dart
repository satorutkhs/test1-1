class WeatherScreen extends StatefulWidget {
  const WeatherScreen({super.key});

  @override
  _WeatherScreenState createState() => _WeatherScreenState();
}

class _WeatherScreenState extends State<WeatherScreen> {
  late Future<List<dynamic>> _forecastData;

  @override
  void initState() {
    super.initState();
    _forecastData = fetchWeatherData();
  }

  Future<List<dynamic>> fetchWeatherData() async {
    final response = await http.get(
      Uri.parse(
        'https://www.jma.go.jp/bosai/forecast/data/forecast/017000.json',
      ),
    );

    if (response.statusCode == 200) {
      return json.decode(response.body);
    } else {
      throw Exception('Failed to load weather data');
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        // TRY THIS: Try changing the color here to a specific color (to
        // Colors.amber, perhaps?) and trigger a hot reload to see the AppBar
        // change color while the other colors stay the same.
        backgroundColor: Theme.of(context).colorScheme.inversePrimary,
        // Here we take the value from the MyHomePage object that was created by
        // the App.build method, and use it to set our appbar title.
        title: const Text('Weather Forecast'),
      ),
      body: FutureBuilder<List<dynamic>>(
        future: _forecastData,
        builder: (context, snapshot) {
          if (snapshot.connectionState == ConnectionState.waiting) {
            return const Center(child: CircularProgressIndicator());
          } else if (snapshot.hasError) {
            return Center(child: Text('Error: ${snapshot.error}'));
          } else if (snapshot.hasData) {
            final data = snapshot.data!;
            return ListView.builder(
              itemCount: data.length,
              itemBuilder: (context, index) {
                final area =
                    data[index]['timeSeries'][0]['areas'][0]['area']['name'];
                final weather =
                    data[index]['timeSeries'][0]['areas'][0]['weathers'][0];
                return ListTile(title: Text(area), subtitle: Text(weather));
              },
            );
          } else {
            return const Center(child: Text('No data available'));
          }
        },
      ),
    );
  }
}
